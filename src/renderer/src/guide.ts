const SEEN_KEY = 'gapgraph.guide.seen'

export function seenVersion(): string {
  try {
    return localStorage.getItem(SEEN_KEY) ?? ''
  } catch {
    return ''
  }
}

export function markSeen(): void {
  try {
    localStorage.setItem(SEEN_KEY, GUIDE_VERSION)
  } catch {
    /* 隐私模式下写不进去，忽略即可 */
  }
}

export function shouldShowGuide(): boolean {
  return seenVersion() !== GUIDE_VERSION
}
